"""Generate module manifests from the pinned MIT CC Switch preset snapshot.

No downloads, credential access or model calls. Run from any working directory.
"""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SNAPSHOT=ROOT/'tools/vendor/cc-switch-opencode-presets.json'
ENTRY='''# Generated by tools/generate_opencode_providers.py; execution is shared.
import json
from pathlib import Path
from hub.builtin_adapters.opencode import provider

def manifest():return json.loads(Path(__file__).with_name('adapter.json').read_text(encoding='utf-8'))
def execute(host,run):return provider.execute(host,run,manifest())
def probe(registry,connection):return provider.probe(registry,connection,manifest())
def probe_model(registry,connection,model):return provider.probe_model(registry,connection,model,manifest())
def setup_status(registry,connection):return provider.status(registry,connection,manifest())
def setup_login(registry,connection):return provider.setup_login(registry,connection,manifest())
def configure(registry,connection,config=None):return provider.configure(registry,connection,manifest(),config)
'''


def generate():
    source=json.loads(SNAPSHOT.read_text(encoding='utf-8'));report=[]
    license=(ROOT/'licenses/cc-switch-MIT.txt').read_text(encoding='utf-8')
    for group in source['groups']:
        report.append({'id':group['id'],'name':group['name'],'variants':len(group['variants']),
                       'status':'skipped' if group.get('skip') else 'generated','reason':group.get('skip','')})
        if group.get('skip'):continue
        folder=ROOT/'hub/builtin_adapters'/group['id'];folder.mkdir(parents=True,exist_ok=True)
        manifest={'version':1,'id':group['id'],'name':'OpenCode【'+group['name']+'】','protocol':'hub-module-v1',
            'entrypoint':'adapter.py','provider':'opencode','efforts':['default'],
            'capabilities':{'tools':True,'resume':True,'streaming':True},'quota_supported':False,
             'configuration':{'version':1,'id':'opencode-provider-v1','title':'供应商配置','fields':[
                {'name':'variant','type':'select','label':'地区 / 套餐','default':group['variants'][0]['id'],
                 'options':[{'value':v['id'],'label':v['name'],'defaults':{'base_url':v['config']['options']['baseURL'],'models':[]}} for v in group['variants']]},
                {'name':'base_url','type':'url','label':'服务地址','default':group['variants'][0]['config']['options']['baseURL']},
                {'name':'api_key','type':'secret','label':'API Key','placeholder':'留空保留已保存密钥'},
                {'name':'key_env','type':'text','label':'或使用密钥环境变量'},
                {'name':'models','type':'string_list','label':'模型 ID（可选，逗号分隔；留空使用预设）'}]},
            'setup':{'website':'https://opencode.ai/','note':'独立 OpenCode 供应商配置；在主程序添加 Agent 界面填写本供应商凭据，不复用原版账号。首次引导可先跳过。'},
            'settings':{'opencode_preset':group},'source':{'repository':source['source'],'commit':source['commit'],'license':'MIT'}}
        (folder/'adapter.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        (folder/'adapter.py').write_text('"""CC Switch preset data license:\n'+license.rstrip()+'\n"""\n'+ENTRY,encoding='utf-8')
    target=ROOT/'docs/OPENCODE_PROVIDERS.json'
    target.write_text(json.dumps({'source_commit':source['commit'],'total':len(report),'generated':sum(r['status']=='generated' for r in report),'providers':report},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return report


if __name__=='__main__':
    rows=generate();print('Generated',sum(r['status']=='generated' for r in rows),'of',len(rows),'provider groups.')
